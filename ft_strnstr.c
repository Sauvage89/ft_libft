#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, unsigned int len)
{
	unsigned int	i;
	unsigned int	j;

	if (*little == 0)
		return ((char *)big);
	i = 0;
	while (big[i] && i < len)
	{
		j = 0;
		while (little[j])
		{
			if (big[i + j] != little[j])
				break ;
			j++;
		}
		if (little[j] == 0)
			return ((char *)little + i);
		i++;
	}
	return (0);
}
